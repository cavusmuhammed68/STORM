def _find_data_root(start: Path) -> Path:
    """Locates the NE_England_real_data folder by searching both upward
    AND into nearby subdirectories from this script's location."""
    required = ["weather_hourly_openmeteo", "electricity_system", "deprivation"]

    def has_data(p: Path) -> bool:
        return all((p / r).is_dir() for r in required)

    searched = []

    def check(p: Path) -> bool:
        searched.append(str(p))
        return has_data(p)

    upward_candidates = [start] + list(start.parents)
    for cand in upward_candidates:
        if check(cand):
            return cand

    for cand in upward_candidates:
        if not cand.is_dir():
            continue
        try:
            subdirs = [p for p in cand.iterdir() if p.is_dir()]
        except (PermissionError, OSError):
            continue
        for sub in subdirs:
            if check(sub):
                return sub

    raise FileNotFoundError(
        "Could not locate the NE_England_real_data folder (expected to find "
        "weather_hourly_openmeteo/, electricity_system/ and deprivation/ all "
        "inside the same directory). Searched:\n  " + "\n  ".join(searched) +
        "\n\nFix: move storm_pipeline.py into NE_England_real_data/code/ "
        "(or anywhere inside/below/beside NE_England_real_data/), so that "
        "weather_hourly_openmeteo/, electricity_system/ and deprivation/ "
        "are reachable either by walking up from the script's own folder, "
        "or by looking one level into a subfolder from there."
    )


