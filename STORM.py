def load_real_electricity() -> pd.DataFrame:
    frames = []
    for year in range(2014, 2024):
        fp = ELEC_DIR / f"demanddata_{year}.csv"
        df = pd.read_csv(fp)
        df["SETTLEMENT_DATE"] = pd.to_datetime(df["SETTLEMENT_DATE"], format="mixed",
                                                 dayfirst=True)
        df["hour"] = ((df["SETTLEMENT_PERIOD"] - 1) // 2).clip(0, 23)
        df["datetime"] = df["SETTLEMENT_DATE"] + pd.to_timedelta(df["hour"], unit="h")
        frames.append(df[["datetime", "ND", "TSD", "EMBEDDED_WIND_GENERATION",
                           "EMBEDDED_WIND_CAPACITY", "EMBEDDED_SOLAR_GENERATION",
                           "EMBEDDED_SOLAR_CAPACITY"]])
    neso = pd.concat(frames, ignore_index=True)
    hourly = neso.groupby("datetime").agg(
        gb_demand_MW=("ND", "mean"),
        gb_tsd_MW=("TSD", "mean"),
        gb_wind_gen_MW=("EMBEDDED_WIND_GENERATION", "mean"),
        gb_wind_cap_MW=("EMBEDDED_WIND_CAPACITY", "mean"),
        gb_solar_gen_MW=("EMBEDDED_SOLAR_GENERATION", "mean"),
        gb_solar_cap_MW=("EMBEDDED_SOLAR_CAPACITY", "mean"),
    ).reset_index()
    hourly["gb_wind_cf"] = hourly.gb_wind_gen_MW / hourly.gb_wind_cap_MW
    hourly["gb_solar_cf"] = (hourly.gb_solar_gen_MW /
                              hourly.gb_solar_cap_MW.replace(0, np.nan)).fillna(0)
    log(f"Loaded real NESO electricity system data (hourly-resampled): "
        f"{hourly.shape[0]:,} rows, {hourly.datetime.min()} to {hourly.datetime.max()}")
