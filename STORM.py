def build_real_network(deprivation: pd.DataFrame) -> Tuple[pd.DataFrame, np.ndarray, np.ndarray]:
    nodes = pd.DataFrame([
        dict(node_id=i, name=name, lat=meta["lat"], lon=meta["lon"],
             coastal=int(meta["coastal"]))
        for i, (name, meta) in enumerate(LOCATIONS.items())
    ])
    nodes = nodes.merge(deprivation, left_on="name", right_on="location", how="left").drop(
        columns=["location"])

    dist = np.zeros((N_NODES, N_NODES))
    for i in range(N_NODES):
        for j in range(N_NODES):
            dist[i, j] = haversine_km(nodes.lat[i], nodes.lon[i], nodes.lat[j], nodes.lon[j])

    k = 3
    adj = np.zeros((N_NODES, N_NODES), dtype="float32")
    for i in range(N_NODES):
        nn_idx = np.argsort(dist[i])[1:k + 1]
        adj[i, nn_idx] = 1.0
        adj[nn_idx, i] = 1.0

    log(f"Built real 12-node network graph (k={k}-NN on great-circle distance), "
        f"mean degree={adj.sum(1).mean():.2f}")
    return nodes, adj, dist


