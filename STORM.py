def batches(X, Y, batch_size=32, shuffle=True):
    X_t, Y_t = torch.tensor(X), torch.tensor(Y)
    idx = np.arange(len(X_t))
    if shuffle:
        RNG.shuffle(idx)
    for i in range(0, len(idx), batch_size):
        b = idx[i:i + batch_size]
        yield X_t[b], Y_t[b]


def evaluate_model(model, X, Y, static_t, forward_kwargs=None) -> Tuple[Dict, np.ndarray]:
    forward_kwargs = forward_kwargs or {}
    model.eval()
    logits_all = []
    with torch.no_grad():
        for xb, _ in batches(X, Y, batch_size=64, shuffle=False):
            out = model(xb, static_t, **forward_kwargs)
            if isinstance(out, tuple):
                out = out[0]
            logits_all.append(out)
    logits_all = torch.cat(logits_all).cpu().numpy()
    metrics = {}
    for i, h in enumerate(HORIZONS):
        y = Y[..., i].ravel()
        p = 1 / (1 + np.exp(-logits_all[..., i].ravel()))
        metrics[h] = dict(
            AUROC=roc_auc_score(y, p) if 0 < y.mean() < 1 else float("nan"),
            AUPRC=average_precision_score(y, p),
            F1=f1_score(y, (p > 0.5).astype(int)),
            Brier=brier_score_loss(y, p),
        )
    return metrics, logits_all


def train_storm(model, Xtr, Ytr, Xva, Yva, static_t, epochs=MAX_EPOCHS, batch_size=32,
                 lr=2e-3, model_name="STORM", patience=EARLY_STOP_PATIENCE) -> Dict:
    opt = torch.optim.Adam(model.parameters(), lr=lr, weight_decay=1e-5)
    sched = torch.optim.lr_scheduler.ReduceLROnPlateau(opt, mode="min", factor=0.5, patience=2)
    history = {"train_loss": [], "val_loss": [], "val_auroc": []}
    best_auroc, best_state, epochs_no_improve = -np.inf, None, 0
    t0 = time.time()

    for epoch in range(1, epochs + 1):
        model.train()
        tr_losses = []
        for xb, yb in batches(Xtr, Ytr, batch_size=batch_size, shuffle=True):
            opt.zero_grad()
            logits = model(xb, static_t)
            if isinstance(logits, tuple):
                logits = logits[0]
            loss = weighted_multi_horizon_loss(logits, yb)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(model.parameters(), 2.0)
            opt.step()
            tr_losses.append(loss.item())

        val_metrics, _ = evaluate_model(model, Xva, Yva, static_t)
        va_losses = []
        model.eval()
        with torch.no_grad():
            for xb, yb in batches(Xva, Yva, batch_size=64, shuffle=False):
                logits = model(xb, static_t)
                if isinstance(logits, tuple):
                    logits = logits[0]
                va_losses.append(weighted_multi_horizon_loss(logits, yb).item())

        tr_loss, va_loss = np.mean(tr_losses), np.mean(va_losses)
        mean_auroc = np.nanmean([m["AUROC"] for m in val_metrics.values()])
        sched.step(va_loss)
        history["train_loss"].append(tr_loss)
        history["val_loss"].append(va_loss)
        history["val_auroc"].append(mean_auroc)
        log(f"[{model_name}] epoch {epoch:02d}/{epochs}  train_loss={tr_loss:.4f}  "
            f"val_loss={va_loss:.4f}  val_AUROC={mean_auroc:.4f}  "
            f"({time.time()-t0:.0f}s elapsed)")

        if mean_auroc > best_auroc + 1e-4:
            best_auroc = mean_auroc
            best_state = {k: v.clone() for k, v in model.state_dict().items()}
            epochs_no_improve = 0
        else:
            epochs_no_improve += 1
            if epochs_no_improve >= patience:
                log(f"[{model_name}] early stopping at epoch {epoch} "
                    f"(no val_AUROC improvement for {patience} epochs); "
                    f"restoring best checkpoint (val_AUROC={best_auroc:.4f}).")
                break

    if best_state is not None:
        model.load_state_dict(best_state)
    log(f"[{model_name}] training complete in {time.time()-t0:.0f}s, best val_AUROC={best_auroc:.4f}")
    return history


