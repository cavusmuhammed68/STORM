def _ensure_dir(path: Path, retries: int = 6, delay: float = 0.25) -> None:
    """Robustly ensures a directory exists immediately before a write.

    Fixes: 'OSError: Cannot save file into a non-existent directory',
    observed when running from a OneDrive-synced folder. Re-asserting the
    directory right before every individual write, with a short retry
    loop, absorbs OneDrive's sync delay instead of crashing the whole
    pipeline on one flaky write.
    """
    for _ in range(retries):
        path.mkdir(parents=True, exist_ok=True)
        if path.is_dir():
            return
        time.sleep(delay)
    raise OSError(f"Could not create or confirm directory exists after "
                  f"{retries} attempts: {path}")


