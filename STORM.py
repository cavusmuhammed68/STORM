def _sankey_ribbon(ax, x0, x1, y0, y1, height, color, alpha=0.55, n=120):
    t = np.linspace(0, 1, n)
    ease = 3 * t ** 2 - 2 * t ** 3
    x_curve = x0 + (x1 - x0) * t
    y_top = y0 + (y1 - y0) * ease
    y_bot = y_top + height
    ax.fill_between(x_curve, y_top, y_bot, color=color, alpha=alpha, lw=0, zorder=1)


def _draw_categorical_sankey(ax, flow: Dict[str, Dict[str, int]],
                              source_order: List[str], target_order: List[str],
                              source_colors: Dict[str, str],
                              target_colors: Dict[str, str],
                              left_title: str, right_title: str,
                              n_note: str) -> None:
    """Draws a two-column categorical Sankey. Both the left (source) and
    right (target) bars use their OWN colour mappings (v2.6: previously
    the right bar fell back to grey when no explicit target colour was
    given; both are now always explicit and colourful)."""
    src_totals = {s: sum(flow[s].values()) for s in source_order}
    tgt_totals = {t: sum(flow[s].get(t, 0) for s in source_order) for t in target_order}
    total = sum(src_totals.values())
    gap = max(0.4, 0.05 * total)

    src_y, y_cursor = {}, 0.0
    for s in source_order:
        src_y[s] = y_cursor
        y_cursor += src_totals[s] + gap
    src_bottom = y_cursor - gap

    tgt_y, y_cursor = {}, 0.0
    for t in target_order:
        tgt_y[t] = y_cursor
        y_cursor += tgt_totals[t] + gap
    tgt_bottom = y_cursor - gap

    ymax = max(src_bottom, tgt_bottom)

    src_cursor = dict(src_y)
    tgt_cursor = dict(tgt_y)
    x_left, x_right = 0.12, 0.88
    for s in source_order:
        for t in target_order:
            cnt = flow[s].get(t, 0)
            if cnt <= 0:
                continue
            _sankey_ribbon(ax, x_left, x_right, src_cursor[s], tgt_cursor[t],
                           height=cnt, color=source_colors[s])
            src_cursor[s] += cnt
            tgt_cursor[t] += cnt

    bar_w = 0.035
    for s in source_order:
        ax.add_patch(Rectangle((x_left - bar_w, src_y[s]), bar_w, max(src_totals[s], 1e-6),
                                facecolor=source_colors[s], edgecolor="black", lw=0.7, zorder=3))
        ax.text(x_left - bar_w - 0.02, src_y[s] + src_totals[s] / 2,
                f"{s}\n(n={src_totals[s]})", ha="right", va="center", fontsize=8.2)
    for t in target_order:
        ax.add_patch(Rectangle((x_right, tgt_y[t]), bar_w, max(tgt_totals[t], 1e-6),
                                facecolor=target_colors[t], edgecolor="black", lw=0.7, zorder=3))
        ax.text(x_right + bar_w + 0.02, tgt_y[t] + tgt_totals[t] / 2,
                f"{t}\n(n={tgt_totals[t]})", ha="left", va="center", fontsize=8.2)

    ax.set_xlim(-0.15, 1.15)
    ax.set_ylim(ymax + gap, -gap * 2.5)
    ax.axis("off")
    ax.text(x_left - bar_w / 2, -gap * 1.6, left_title, ha="center", fontsize=9.5, fontweight="bold")
    ax.text(x_right + bar_w / 2, -gap * 1.6, right_title, ha="center", fontsize=9.5, fontweight="bold")
    ax.text(0.5, ymax + gap * 2.0, n_note, ha="center", fontsize=7.6, style="italic", color="#555555")


