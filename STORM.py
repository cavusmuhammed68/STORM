def permutation_importance(model, X, Y, static_t, horizon_idx, n_repeats=3,
                            n_subset=300) -> Tuple[np.ndarray, float]:
    sub = RNG.choice(len(X), size=min(n_subset, len(X)), replace=False)
    Xs, Ys = X[sub], Y[sub]
    model.eval()
    with torch.no_grad():
        base_logits = model(torch.tensor(Xs), static_t)
        if isinstance(base_logits, tuple):
            base_logits = base_logits[0]
        base_logits = base_logits[..., horizon_idx].cpu().numpy()
    y_flat = Ys[..., horizon_idx].ravel()
    base_auc = roc_auc_score(y_flat, 1 / (1 + np.exp(-base_logits.ravel())))

    importances = []
    for f in range(Xs.shape[-1]):
        drops = []
        for _ in range(n_repeats):
            Xp = Xs.copy()
            perm = RNG.permutation(Xp.shape[0])
            Xp[..., f] = Xp[perm][..., f]
            with torch.no_grad():
                logit_p = model(torch.tensor(Xp), static_t)
                if isinstance(logit_p, tuple):
                    logit_p = logit_p[0]
                logit_p = logit_p[..., horizon_idx].cpu().numpy()
            auc_p = roc_auc_score(y_flat, 1 / (1 + np.exp(-logit_p.ravel())))
            drops.append(base_auc - auc_p)
        importances.append(np.mean(drops))
    return np.array(importances), base_auc


