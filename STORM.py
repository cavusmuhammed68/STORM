def spatial_generalisation_table(nodes: pd.DataFrame, Yte: np.ndarray,
                                  logits_storm: np.ndarray, n_boot: int = 500) -> pd.DataFrame:
    idx6 = HORIZONS.index(6)
    rng = np.random.default_rng(SEED)
    rows = []
    for n in range(N_NODES):
        y = Yte[:, n, idx6]
        p = 1 / (1 + np.exp(-logits_storm[:, n, idx6]))
        if 0 < y.mean() < 1:
            auroc = roc_auc_score(y, p)
            nlen = len(y)
            boots = []
            for _ in range(n_boot):
                bidx = rng.integers(0, nlen, nlen)
                yt, yp = y[bidx], p[bidx]
                if 0 < yt.mean() < 1:
                    boots.append(roc_auc_score(yt, yp))
            lo, hi = (np.percentile(boots, [2.5, 97.5]) if boots else (np.nan, np.nan))
        else:
            auroc, lo, hi = float("nan"), np.nan, np.nan
        rows.append(dict(node=nodes.name[n], coastal=bool(nodes.coastal[n]),
                          IMD_decile=int(nodes.IMD_decile[n]),
                          n_test_windows=len(y), positive_rate_pct=round(y.mean() * 100, 2),
                          AUROC_6h=round(auroc, 4) if not np.isnan(auroc) else None,
                          AUROC_6h_CI_lo=round(lo, 4) if not np.isnan(lo) else None,
                          AUROC_6h_CI_hi=round(hi, 4) if not np.isnan(hi) else None,
                          AUPRC_6h=round(average_precision_score(y, p), 4)))
    df = pd.DataFrame(rows)
    save_csv(df, TAB_DIR / "table8_spatial_generalisation.csv", index=False)
    log(f"Saved table8_spatial_generalisation.csv ({len(df)} nodes, with bootstrap 95% CIs)")
    return df


def decision_curve_analysis(y_val: np.ndarray, p_val: np.ndarray,
                             y_test: np.ndarray, p_test: np.ndarray,
                             cost_ratios=(0.05, 0.1, 0.2, 0.3, 0.5)) -> pd.DataFrame:
    thresholds = np.linspace(0.01, 0.99, 99)
    rows = []
    n_val = len(y_val)
    for cr in cost_ratios:
        best_nb, best_t = -np.inf, 0.5
        for t in thresholds:
            pred = (p_val > t).astype(int)
            tp = int(np.sum((pred == 1) & (y_val == 1)))
            fp = int(np.sum((pred == 1) & (y_val == 0)))
            nb = (tp / n_val) - (fp / n_val) * cr
            if nb > best_nb:
                best_nb, best_t = nb, t
        pred_test = (p_test > best_t).astype(int)
        tp_t = int(np.sum((pred_test == 1) & (y_test == 1)))
        fp_t = int(np.sum((pred_test == 1) & (y_test == 0)))
        nb_test = (tp_t / len(y_test)) - (fp_t / len(y_test)) * cr
        rows.append(dict(cost_ratio_FP_to_TP=cr, threshold_selected_on_validation=round(best_t, 2),
                          net_benefit_on_validation=round(best_nb, 5),
                          net_benefit_on_held_out_test=round(nb_test, 5)))
    df = pd.DataFrame(rows)
    save_csv(df, TAB_DIR / "table9_decision_curve_thresholds.csv", index=False)
    log("Saved table9_decision_curve_thresholds.csv (threshold selected on validation, "
        "net benefit reported on held-out test)")
    return df


def robustness_to_noise(model, X, Y, static_t, horizon_idx,
                         noise_levels=(0.0, 0.1, 0.25, 0.5, 1.0)) -> pd.DataFrame:
    gust_idx = DYNAMIC_FEATURES.index("wind_gusts_10m")
    rows = []
    model.eval()
    for sigma in noise_levels:
        Xp = X.copy()
        Xp[..., gust_idx] += RNG.normal(0, sigma, Xp[..., gust_idx].shape)
        with torch.no_grad():
            logits = model(torch.tensor(Xp), static_t)
            if isinstance(logits, tuple):
                logits = logits[0]
        y = Y[..., horizon_idx].ravel()
        p = 1 / (1 + np.exp(-logits[..., horizon_idx].cpu().numpy().ravel()))
        rows.append(dict(noise_sigma=sigma, AUROC=roc_auc_score(y, p) if 0 < y.mean() < 1 else np.nan,
                          AUPRC=average_precision_score(y, p)))
    df = pd.DataFrame(rows)
    save_csv(df, TAB_DIR / "table11_robustness_to_noise.csv", index=False)
    log(f"Saved table11_robustness_to_noise.csv -- AUROC at sigma=0: "
        f"{df.AUROC.iloc[0]:.4f}, at sigma={noise_levels[-1]}: {df.AUROC.iloc[-1]:.4f}")
    return df


