def bootstrap_auroc_ci(y_true, y_prob, n_boot=1000, alpha=0.05) -> Tuple[float, float, float]:
    rng = np.random.default_rng(SEED)
    n = len(y_true)
    boots = []
    for _ in range(n_boot):
        idx = rng.integers(0, n, n)
        yt, yp = y_true[idx], y_prob[idx]
        if 0 < yt.mean() < 1:
            boots.append(roc_auc_score(yt, yp))
    boots = np.array(boots)
    point = roc_auc_score(y_true, y_prob)
    lo, hi = np.percentile(boots, [100 * alpha / 2, 100 * (1 - alpha / 2)])
    return point, lo, hi


def mcnemar_test(y_true, p_a, p_b, threshold=0.5) -> Tuple[float, float]:
    pred_a = (p_a > threshold).astype(int)
    pred_b = (p_b > threshold).astype(int)
    correct_a = (pred_a == y_true)
    correct_b = (pred_b == y_true)
    b01 = int(np.sum(correct_a & ~correct_b))
    b10 = int(np.sum(~correct_a & correct_b))
    n = b01 + b10
    if n == 0:
        return 0.0, 1.0
    stat = (abs(b01 - b10) - 1) ** 2 / n
    p_value = 1 - scipy_stats.chi2.cdf(stat, df=1)
    return stat, p_value


