class FeatureDropout(nn.Module):
    def __init__(self, p: float = FEATURE_DROPOUT_P):
        super().__init__()
        self.p = p

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        if not self.training or self.p <= 0:
            return x
        B = x.shape[0]
        Fd = x.shape[-1]
        drop_shape = (B,) + (1,) * (x.dim() - 2) + (Fd,)
        keep = (torch.rand(drop_shape, device=x.device) > self.p).float()
        return x * keep / (1 - self.p)


class GraphAttentionLayer(nn.Module):
    def __init__(self, in_dim, out_dim, n_heads, adj_mask):
        super().__init__()
        self.n_heads, self.out_dim = n_heads, out_dim
        self.W = nn.Linear(in_dim, out_dim * n_heads, bias=False)
        self.a_src = nn.Parameter(torch.empty(n_heads, out_dim))
        self.a_dst = nn.Parameter(torch.empty(n_heads, out_dim))
        nn.init.xavier_uniform_(self.a_src.unsqueeze(0))
        nn.init.xavier_uniform_(self.a_dst.unsqueeze(0))
        self.register_buffer("mask", adj_mask)
        self.leaky = nn.LeakyReLU(0.2)
        self.out_proj = nn.Linear(out_dim * n_heads, out_dim)

    def forward(self, x, return_attn=False):
        B, N, _ = x.shape
        h = self.W(x).view(B, N, self.n_heads, self.out_dim)
        src = torch.einsum("bnhd,hd->bnh", h, self.a_src)
        dst = torch.einsum("bnhd,hd->bnh", h, self.a_dst)
        e = self.leaky(src.unsqueeze(2) + dst.unsqueeze(1))
        e = e.masked_fill(self.mask.unsqueeze(0).unsqueeze(-1) == 0, float("-1e9"))
        alpha = torch.softmax(e, dim=2)
        out = torch.einsum("bijh,bjhd->bihd", alpha, h).reshape(B, N, self.n_heads * self.out_dim)
        out = F.elu(self.out_proj(out))
        if return_attn:
            return out, alpha
        return out, None


class GATStack(nn.Module):
    """A stack of `n_layers` GraphAttentionLayer blocks, each operating
    in `gat_dim`-dimensional space after the first layer, with a
    residual (additive) connection between consecutive layers once
    their input/output dimensions match. Shared "deeper spatial encoder"
    building block used identically by STORM and GAT-only."""

    def __init__(self, f_dyn, gat_dim, n_heads, adj_mask, n_layers=GAT_LAYERS):
        super().__init__()
        blocks = []
        in_dim = f_dyn
        for _ in range(n_layers):
            blocks.append(GraphAttentionLayer(in_dim, gat_dim, n_heads, adj_mask))
            in_dim = gat_dim
        self.blocks = nn.ModuleList(blocks)

    def forward(self, x_flat, return_attn=False):
        h = x_flat
        last_attn = None
        for i, block in enumerate(self.blocks):
            out, attn = block(h, return_attn=return_attn)
            if i > 0 and out.shape == h.shape:
                out = out + h
            h = out
            if return_attn:
                last_attn = attn
        return h, last_attn


class GatedFusion(nn.Module):
    def __init__(self, dim):
        super().__init__()
        self.gate = nn.Linear(dim * 2, dim)
        self.transform = nn.Linear(dim * 2, dim)

    def forward(self, h_dyn, h_static):
        cat = torch.cat([h_dyn, h_static], dim=-1)
        g = torch.sigmoid(self.gate(cat))
        t = torch.tanh(self.transform(cat))
        return g * t + (1 - g) * h_dyn


class STORM(nn.Module):
    """Full STORM model: FeatureDropout -> 2-layer residual GAT stack ->
    shared LSTM (with a residual skip connection bridging it) -> gated
    static fusion -> multi-horizon head."""

    def __init__(self, f_dyn, f_stat, adj_mask, gat_dim=16, gat_heads=GAT_HEADS,
                 lstm_hidden=48, n_horizons=len(HORIZONS), mc_dropout_p=0.15,
                 feature_dropout_p=FEATURE_DROPOUT_P, gat_layers=GAT_LAYERS):
        super().__init__()
        self.feat_dropout = FeatureDropout(feature_dropout_p)
        self.gat_stack = GATStack(f_dyn, gat_dim, gat_heads, adj_mask, n_layers=gat_layers)
        self.lstm = nn.LSTM(gat_dim, lstm_hidden, batch_first=True)
        self.skip_proj = nn.Linear(gat_dim, lstm_hidden)
        self.static_proj = nn.Sequential(
            nn.Linear(f_stat, lstm_hidden), nn.ReLU(), nn.Linear(lstm_hidden, lstm_hidden))
        self.fusion = GatedFusion(lstm_hidden)
        self.mc_dropout_p = mc_dropout_p
        self.head = nn.Sequential(
            nn.Linear(lstm_hidden, 32), nn.ReLU(), nn.Dropout(mc_dropout_p),
            nn.Linear(32, n_horizons))
        self.lstm_hidden = lstm_hidden

    def forward(self, x, static_feats, return_attn=False):
        x = self.feat_dropout(x)
        Bsz, T, N, Fd = x.shape
        x_flat = x.reshape(Bsz * T, N, Fd)
        g_flat, attn = self.gat_stack(x_flat, return_attn=return_attn)
        gat_seq = g_flat.view(Bsz, T, N, -1).permute(0, 2, 1, 3).reshape(Bsz * N, T, -1)
        _, (hn, _) = self.lstm(gat_seq)
        h_dyn = hn[-1].view(Bsz, N, self.lstm_hidden)
        skip = self.skip_proj(gat_seq.mean(dim=1)).view(Bsz, N, self.lstm_hidden)
        h_dyn = h_dyn + skip
        h_stat = self.static_proj(static_feats).unsqueeze(0).expand(Bsz, -1, -1)
        fused = self.fusion(h_dyn, h_stat)
        logits = self.head(fused)
        if return_attn:
            return logits, attn
        return logits

    def predict_with_uncertainty(self, x, static_feats, mc_samples=30):
        self.train()
        self.feat_dropout.eval()
        with torch.no_grad():
            probs = torch.stack([torch.sigmoid(self.forward(x, static_feats))
                                  for _ in range(mc_samples)], dim=0)
        self.eval()
        return probs.mean(0), probs.std(0)

    def get_node_attention_matrix(self, x_window: torch.Tensor, static_feats: torch.Tensor) -> np.ndarray:
        self.eval()
        with torch.no_grad():
            x_last = x_window[:, -1]
            h = x_last
            attn = None
            for i, block in enumerate(self.gat_stack.blocks):
                out, a = block(h, return_attn=True)
                if i > 0 and out.shape == h.shape:
                    out = out + h
                h = out
                attn = a
        return attn[0].mean(dim=-1).cpu().numpy()


class LSTMOnlyAblation(nn.Module):
    """Ablation: no graph component at all. Receives the same
    residual/skip enhancement given to STORM/GCN-only, using its own
    (non-graph) time-mean-pooled raw covariates as the skip source."""

    def __init__(self, f_dyn, f_stat, lstm_hidden=48, n_horizons=len(HORIZONS),
                 feature_dropout_p=FEATURE_DROPOUT_P):
        super().__init__()
        self.feat_dropout = FeatureDropout(feature_dropout_p)
        self.lstm = nn.LSTM(f_dyn, lstm_hidden, batch_first=True)
        self.skip_proj = nn.Linear(f_dyn, lstm_hidden)
        self.static_proj = nn.Sequential(
            nn.Linear(f_stat, lstm_hidden), nn.ReLU(), nn.Linear(lstm_hidden, lstm_hidden))
        self.fusion = GatedFusion(lstm_hidden)
        self.head = nn.Sequential(nn.Linear(lstm_hidden, 32), nn.ReLU(),
                                   nn.Dropout(0.15), nn.Linear(32, n_horizons))
        self.lstm_hidden = lstm_hidden

    def forward(self, x, static_feats):
        x = self.feat_dropout(x)
        Bsz, T, N, Fd = x.shape
        xr = x.permute(0, 2, 1, 3).reshape(Bsz * N, T, Fd)
        _, (hn, _) = self.lstm(xr)
        h_dyn = hn[-1].view(Bsz, N, self.lstm_hidden)
        skip = self.skip_proj(xr.mean(dim=1)).view(Bsz, N, self.lstm_hidden)
        h_dyn = h_dyn + skip
        h_stat = self.static_proj(static_feats).unsqueeze(0).expand(Bsz, -1, -1)
        return self.head(self.fusion(h_dyn, h_stat))


class GATOnlyAblation(nn.Module):
    """Ablation: no temporal memory. Uses the same 2-layer residual GAT
    stack and 6 attention heads as STORM."""

    def __init__(self, f_dyn, f_stat, adj_mask, gat_dim=16, gat_heads=GAT_HEADS,
                 lstm_hidden=48, n_horizons=len(HORIZONS),
                 feature_dropout_p=FEATURE_DROPOUT_P, gat_layers=GAT_LAYERS):
        super().__init__()
        self.feat_dropout = FeatureDropout(feature_dropout_p)
        self.gat_stack = GATStack(f_dyn, gat_dim, gat_heads, adj_mask, n_layers=gat_layers)
        self.temporal_proj = nn.Linear(gat_dim, lstm_hidden)
        self.static_proj = nn.Sequential(
            nn.Linear(f_stat, lstm_hidden), nn.ReLU(), nn.Linear(lstm_hidden, lstm_hidden))
        self.fusion = GatedFusion(lstm_hidden)
        self.head = nn.Sequential(nn.Linear(lstm_hidden, 32), nn.ReLU(),
                                   nn.Dropout(0.15), nn.Linear(32, n_horizons))

    def forward(self, x, static_feats):
        x = self.feat_dropout(x)
        Bsz, T, N, Fd = x.shape
        x_flat = x.reshape(Bsz * T, N, Fd)
        g_flat, _ = self.gat_stack(x_flat)
        g_seq = g_flat.view(Bsz, T, N, -1)
        pooled = g_seq.mean(dim=1)
        h_dyn = F.relu(self.temporal_proj(pooled))
        h_stat = self.static_proj(static_feats).unsqueeze(0).expand(Bsz, -1, -1)
        return self.head(self.fusion(h_dyn, h_stat))


class GCNStack(nn.Module):
    """Fixed-weight (degree-normalised neighbour-averaging) analogue of
    GATStack, with the same depth and residual connections, giving
    GCN-only the same spatial-encoder depth as STORM/GAT-only."""

    def __init__(self, f_dyn, gcn_dim, adj_norm, n_layers=GAT_LAYERS):
        super().__init__()
        self.register_buffer("adj_norm", adj_norm)
        projs = []
        in_dim = f_dyn
        for _ in range(n_layers):
            projs.append(nn.Linear(in_dim, gcn_dim))
            in_dim = gcn_dim
        self.projs = nn.ModuleList(projs)

    def forward(self, x_flat):
        h = x_flat
        for i, proj in enumerate(self.projs):
            out = F.relu(proj(h))
            out = torch.einsum("ij,bjd->bid", self.adj_norm, out)
            if i > 0 and out.shape == h.shape:
                out = out + h
            h = out
        return h


class GCNOnlyAblation(nn.Module):
    """Ablation: fixed-weight graph convolution instead of learned
    attention, ahead of the same LSTM + fusion + head used by STORM.
    Uses a 2-layer residual GCNStack (matching STORM's GAT depth) AND
    the same residual/skip bridging the LSTM as STORM/LSTM-only."""

    def __init__(self, f_dyn, f_stat, adj_mask, gcn_dim=16, lstm_hidden=48,
                 n_horizons=len(HORIZONS), feature_dropout_p=FEATURE_DROPOUT_P,
                 gcn_layers=GAT_LAYERS):
        super().__init__()
        self.feat_dropout = FeatureDropout(feature_dropout_p)
        adj_norm = self._normalise_adj(adj_mask)
        self.gcn_stack = GCNStack(f_dyn, gcn_dim, adj_norm, n_layers=gcn_layers)
        self.lstm = nn.LSTM(gcn_dim, lstm_hidden, batch_first=True)
        self.skip_proj = nn.Linear(gcn_dim, lstm_hidden)
        self.static_proj = nn.Sequential(
            nn.Linear(f_stat, lstm_hidden), nn.ReLU(), nn.Linear(lstm_hidden, lstm_hidden))
        self.fusion = GatedFusion(lstm_hidden)
        self.head = nn.Sequential(nn.Linear(lstm_hidden, 32), nn.ReLU(),
                                   nn.Dropout(0.15), nn.Linear(32, n_horizons))
        self.lstm_hidden = lstm_hidden

    @staticmethod
    def _normalise_adj(adj_mask):
        deg = adj_mask.sum(1, keepdim=True).clamp(min=1.0)
        return adj_mask / deg

    def forward(self, x, static_feats):
        x = self.feat_dropout(x)
        Bsz, T, N, Fd = x.shape
        x_flat = x.reshape(Bsz * T, N, Fd)
        h = self.gcn_stack(x_flat)
        gcn_seq = h.view(Bsz, T, N, -1).permute(0, 2, 1, 3).reshape(Bsz * N, T, -1)
        _, (hn, _) = self.lstm(gcn_seq)
        h_dyn = hn[-1].view(Bsz, N, self.lstm_hidden)
        skip = self.skip_proj(gcn_seq.mean(dim=1)).view(Bsz, N, self.lstm_hidden)
        h_dyn = h_dyn + skip
        h_stat = self.static_proj(static_feats).unsqueeze(0).expand(Bsz, -1, -1)
        return self.head(self.fusion(h_dyn, h_stat))


def focal_loss(logits, targets, gamma=2.0, alpha=0.25):
    p = torch.sigmoid(logits)
    ce = F.binary_cross_entropy_with_logits(logits, targets, reduction="none")
    p_t = p * targets + (1 - p) * (1 - targets)
    return (alpha * (1 - p_t) ** gamma * ce).mean()


HORIZON_WEIGHTS = torch.tensor([1.4, 1.2, 1.0, 0.9, 0.8])


def weighted_multi_horizon_loss(logits, targets):
    per_h = torch.stack([focal_loss(logits[..., i], targets[..., i])
                          for i in range(len(HORIZONS))])
    return (per_h * HORIZON_WEIGHTS).sum() / HORIZON_WEIGHTS.sum()


