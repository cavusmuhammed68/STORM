def main():
    t_start = time.time()
    log("=" * 70)
    log("STORM pipeline (v2.6) starting -- real North East England digital twin")
    log("=" * 70)
    validate_environment()
    cfg = RunConfig()
    cfg.save(RESULTS_DIR / "run_config.json")

    # ---- 1. Real data ----
    weather = load_real_weather()
    electricity = load_real_electricity()
    deprivation = load_real_deprivation_and_match()
    nodes, adj, dist_matrix = build_real_network(deprivation)
    adj_self = adj + np.eye(N_NODES, dtype="float32")
    adj_mask = torch.tensor((adj_self > 0).astype("float32"))


    # ---- 2. Raw features, outage labels, THEN multicollinearity screening ----
    feature_stack_raw, time_index = engineer_features(weather, electricity)
    trip = generate_outage_labels(feature_stack_raw, nodes, time_index, adj, dist_matrix)
    labels = build_multi_horizon_labels(trip)

    feature_stack_model, active_features, vif_report = prune_correlated_features(
        feature_stack_raw, RAW_DYNAMIC_FEATURES)
    DYNAMIC_FEATURES[:] = active_features
    log(f"Active dynamic feature set used by the model: {DYNAMIC_FEATURES}")

    feature_stack_norm, mu, sd = standardise(feature_stack_model)
    dataset = build_windows(feature_stack_norm, labels, time_index)

    static_raw = nodes[STATIC_FEATURES].values.astype("float32")
    static_norm = (static_raw - static_raw.mean(0)) / (static_raw.std(0) + 1e-6)
    static_t = torch.tensor(static_norm)

    Xtr, Ytr = dataset["Xtr"], dataset["Ytr"]
    Xva, Yva = dataset["Xva"], dataset["Yva"]
    Xte, Yte = dataset["Xte"], dataset["Yte"]

    # ---- 3. Train STORM + ablations ----
    log("-" * 70); log("Training STORM (full model)"); log("-" * 70)
    storm = STORM(len(DYNAMIC_FEATURES), len(STATIC_FEATURES), adj_mask)
    n_params = sum(p.numel() for p in storm.parameters())
    log(f"STORM parameter count: {n_params:,}")
    train_storm(storm, Xtr, Ytr, Xva, Yva, static_t, model_name="STORM")

    log("-" * 70); log("Training LSTM-only ablation"); log("-" * 70)
    lstm_only = LSTMOnlyAblation(len(DYNAMIC_FEATURES), len(STATIC_FEATURES))
    train_storm(lstm_only, Xtr, Ytr, Xva, Yva, static_t, model_name="LSTM-only")

    log("-" * 70); log("Training GAT-only ablation (no temporal memory)"); log("-" * 70)
    gat_only = GATOnlyAblation(len(DYNAMIC_FEATURES), len(STATIC_FEATURES), adj_mask)
    train_storm(gat_only, Xtr, Ytr, Xva, Yva, static_t, model_name="GAT-only")

    log("-" * 70); log("Training GCN-only ablation (fixed-weight graph conv, no attention)"); log("-" * 70)
    gcn_only = GCNOnlyAblation(len(DYNAMIC_FEATURES), len(STATIC_FEATURES), adj_mask)
    train_storm(gcn_only, Xtr, Ytr, Xva, Yva, static_t, model_name="GCN-only")

    log("-" * 70); log("Training classical baselines (LogReg, RandForest, GradBoost)"); log("-" * 70)
    baseline_results, baseline_preds_all_h = train_baselines(Xtr, Ytr, Xte, Yte, static_norm)

    # ---- 4. Evaluation on held-out test set ----
    log("-" * 70); log("Evaluating all models on the held-out 2022-2023 test set"); log("-" * 70)
    metrics_storm, logits_storm = evaluate_model(storm, Xte, Yte, static_t)
    metrics_lstm, logits_lstm = evaluate_model(lstm_only, Xte, Yte, static_t)
    metrics_gat, logits_gat = evaluate_model(gat_only, Xte, Yte, static_t)
    metrics_gcn, logits_gcn = evaluate_model(gcn_only, Xte, Yte, static_t)
    for h in HORIZONS:
        log(f"  STORM      {h:>2}h  AUROC={metrics_storm[h]['AUROC']:.4f}  "
            f"AUPRC={metrics_storm[h]['AUPRC']:.4f}  F1={metrics_storm[h]['F1']:.4f}")
        log(f"  LSTM-only  {h:>2}h  AUROC={metrics_lstm[h]['AUROC']:.4f}  "
            f"AUPRC={metrics_lstm[h]['AUPRC']:.4f}")
        log(f"  GAT-only   {h:>2}h  AUROC={metrics_gat[h]['AUROC']:.4f}  "
            f"AUPRC={metrics_gat[h]['AUPRC']:.4f}")
        log(f"  GCN-only   {h:>2}h  AUROC={metrics_gcn[h]['AUROC']:.4f}  "
            f"AUPRC={metrics_gcn[h]['AUPRC']:.4f}")

    idx6 = HORIZONS.index(6)
    y6 = Yte[..., idx6].ravel()
    p6_storm = 1 / (1 + np.exp(-logits_storm[..., idx6].ravel()))
    cm6 = confusion_matrix(y6, (p6_storm > 0.5).astype(int))

    point, lo, hi = bootstrap_auroc_ci(y6, p6_storm)
    log(f"STORM 6h AUROC bootstrap 95% CI: {point:.4f} [{lo:.4f}, {hi:.4f}]")

    # ---- 4b. STORM on VALIDATION set (needed for calibration + decision curve) ----
    metrics_storm_val, logits_storm_val = evaluate_model(storm, Xva, Yva, static_t)
    yva6 = Yva[..., idx6].ravel()
    pva6 = 1 / (1 + np.exp(-logits_storm_val[..., idx6].ravel()))

    # ---- 5. Multi-horizon, Holm-corrected significance testing + full bootstrap ----
    log("-" * 70); log("Statistical testing across all horizons"); log("-" * 70)
    logit_dict = {"STORM": logits_storm, "LSTM_only": logits_lstm,
                  "GAT_only": logits_gat, "GCN_only": logits_gcn}
    preds_by_h, y_by_h = collect_all_predictions(Yte, logit_dict, baseline_preds_all_h)
    holm_df = multi_horizon_mcnemar(preds_by_h, y_by_h)
    bootstrap_all_df = full_bootstrap_table(preds_by_h, y_by_h)
    boot_dist = compute_bootstrap_distributions(preds_by_h, y_by_h)
    

    # ---- 6. Calibration (table only; figure removed -- see revision note 21) ----
    log("-" * 70); log("Post-hoc calibration (temperature scaling, fit on validation)"); log("-" * 70)
    temperatures = {}
    for i, h in enumerate(HORIZONS):
        temperatures[h] = fit_temperature_scaling(
            logits_storm_val[..., i].ravel(), Yva[..., i].ravel())
    log(f"Fitted per-horizon calibration temperatures: "
        f"{ {h: round(t,3) for h,t in temperatures.items()} }")
    calib_df = calibration_report(Yte, logits_storm, temperatures)

    # ---- 7. Interpretability, uncertainty, spatial diagnostics ----
    log("-" * 70); log("Interpretability and uncertainty analysis"); log("-" * 70)
    importances, base_auc = permutation_importance(storm, Xte, Yte, static_t, idx6)
    log(f"Individual permutation importance computed (base AUROC={base_auc:.4f})")

    family_groups_idx: Dict[str, List[int]] = {}
    for i, name in enumerate(DYNAMIC_FEATURES):
        fam = FEATURE_FAMILIES.get(name, "Other")
        family_groups_idx.setdefault(fam, []).append(i)
    grouped_df = grouped_permutation_importance(storm, Xte, Yte, static_t, idx6, family_groups_idx)

    mc_mean, mc_std = storm.predict_with_uncertainty(torch.tensor(Xte), static_t, mc_samples=30)
    mc_mean_6h = mc_mean[..., idx6].cpu().numpy().ravel()
    mc_std_6h = mc_std[..., idx6].cpu().numpy().ravel()

    p6_node = 1 / (1 + np.exp(-logits_storm[..., idx6])).mean(axis=0)
    moran_val = morans_i(p6_node, nodes[["lon", "lat"]].values)

    attn_matrix = storm.get_node_attention_matrix(torch.tensor(Xte[-1:]), static_t)

    arwen_time = pd.Timestamp("2021-11-26 22:00:00")
    arwen_idx = np.where(time_index == arwen_time)[0]
    raw_gust_col = RAW_DYNAMIC_FEATURES.index("wind_gusts_10m")
    if len(arwen_idx):
        storm_snapshot = feature_stack_raw[arwen_idx[0], :, raw_gust_col]
    else:
        storm_snapshot = feature_stack_raw[:, :, raw_gust_col].max(axis=0)
    log(f"Real Storm Arwen snapshot wind gusts (m/s): "
        f"{dict(zip(nodes.name, np.round(storm_snapshot, 1)))}")

    # ---- 8. Extended analysis ----
    log("-" * 70); log("Extended analysis"); log("-" * 70)
    descriptive_weather_statistics(weather)
    spatial_df = spatial_generalisation_table(nodes, Yte, logits_storm)
    decision_df = decision_curve_analysis(yva6, pva6, y6, p6_storm)
    data_quality_report(weather, electricity)
    saliency = gradient_saliency(storm, Xte, static_t, idx6)
    robustness_df = robustness_to_noise(storm, Xte, Yte, static_t, idx6)

    # ---- 9. Tables ----
    log("-" * 70); log("Generating tables"); log("-" * 70)
    tables = build_tables(nodes, dataset, metrics_storm, metrics_lstm, metrics_gat,
                           baseline_results, cm6, n_params, moran_val)
    table3 = tables["table3_model_comparison"]
    table3["GCN_only_AUROC"] = [metrics_gcn[h]["AUROC"] for h in HORIZONS]
    table3["GCN_only_AUPRC"] = [metrics_gcn[h]["AUPRC"] for h in HORIZONS]
    table3["GCN_only_F1"] = [metrics_gcn[h]["F1"] for h in HORIZONS]
    table3["GCN_only_Brier"] = table3["STORM_Brier"]
    table3["STORM_Brier_calibrated"] = calib_df.set_index("horizon").loc[
        table3["Horizon"], "brier_calibrated"].values
    save_csv(table3, TAB_DIR / "table3_model_comparison.csv", index=False)

    # ---- 10. Figures ----
    log("-" * 70); log("Generating 600 DPI PNG figures"); log("-" * 70)
    figure_multipanel_maps(nodes, adj, p6_node, attn_matrix, storm_snapshot)          # MAP
    figure_storm_evolution_maps(nodes, feature_stack_raw, time_index, adj)            # MAP
    figure_equity_dualburden_map(nodes, p6_node)                                      # MAP
    figure_spatial_generalisation_map(nodes, spatial_df)                              # MAP
    figure_leadtime_trend(metrics_storm, metrics_lstm, metrics_gcn)
    figure_roc_pr(Yte, logits_storm, logits_lstm, preds_by_h)
    figure_probability_ridgeline(logits_storm, Yte)
    figure_seasonal_polar(weather)
    figure_feature_importance_combined(importances, DYNAMIC_FEATURES, grouped_df)
    figure_decision_robustness_combo(y6, p6_storm, decision_df, robustness_df)
    figure_real_storm_case_studies(nodes, feature_stack_raw, time_index)
    figure_correlation_heatmap(feature_stack_raw, RAW_DYNAMIC_FEATURES)
    figure_temporal_saliency(saliency, DYNAMIC_FEATURES)
    figure_sankey_combined(nodes, p6_node)                                            # v2.6
    figure_model_comparison_slope(boot_dist, holm_df)                                 # v2.7, fig5a

    write_technical_appendix(n_params, sum(p.numel() for p in lstm_only.parameters()),
                              sum(p.numel() for p in gat_only.parameters()),
                              metrics_storm, moran_val, (point, lo, hi), calib_df, holm_df)

    # ---- 11. Persist model + evaluation artefacts for reproducibility ----
    save_torch({"state_dict": storm.state_dict(),
                "config": {"f_dyn": len(DYNAMIC_FEATURES), "f_stat": len(STATIC_FEATURES),
                           "n_nodes": N_NODES, "active_features": DYNAMIC_FEATURES,
                           "gat_layers": GAT_LAYERS, "gat_heads": GAT_HEADS}},
               TAB_DIR / "storm_checkpoint.pt")
    save_npz(TAB_DIR / "eval_artifacts.npz",
             logits_storm=logits_storm, logits_lstm=logits_lstm,
             logits_gat=logits_gat, logits_gcn=logits_gcn, Yte=Yte, cm6=cm6,
             p6_node=p6_node, attn_matrix=attn_matrix, importances=importances,
             mc_mean_6h=mc_mean_6h, mc_std_6h=mc_std_6h, saliency=saliency,
             bootstrap_ci=np.array([point, lo, hi]))

    save_json({"STORM": metrics_storm, "LSTM_only": metrics_lstm,
               "GAT_only": metrics_gat, "GCN_only": metrics_gcn,
               "baselines": baseline_results,
               "bootstrap_6h_AUROC_CI": {"point": point, "lo": lo, "hi": hi},
               "n_params_storm": n_params, "morans_i": moran_val,
               "active_dynamic_features": DYNAMIC_FEATURES,
               "calibration_temperatures": temperatures,
               "holm_corrected_significance": holm_df.to_dict("records"),
               "grouped_permutation_importance": grouped_df.to_dict("records"),
               "bootstrap_all_models": bootstrap_all_df.to_dict("records")},
              TAB_DIR / "metrics_summary.json", indent=2)

    log("=" * 70)
    log(f"STORM pipeline complete in {time.time()-t_start:.0f}s. "
        f"Results in {RESULTS_DIR}")
    log("=" * 70)
    print_final_summary(metrics_storm, n_params, moran_val, (point, lo, hi), calib_df,
                         time.time() - t_start)


