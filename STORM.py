def engineer_features(weather: pd.DataFrame, electricity: pd.DataFrame) -> Tuple[np.ndarray, pd.DatetimeIndex]:
    pivot = {}
    for col in ["wind_speed_10m", "wind_gusts_10m", "precipitation",
                "temperature_2m", "relative_humidity_2m", "surface_pressure",
                "cloud_cover"]:
        pivot[col] = weather.pivot(index="time", columns="location", values=col)[NODE_NAMES].values

    time_index = weather.pivot(index="time", columns="location",
                                values="wind_speed_10m")[NODE_NAMES].index
    T = len(time_index)

    gust_cubed = (pivot["wind_gusts_10m"] / 25.0) ** 3
    rain_accum_3h = pd.DataFrame(pivot["precipitation"]).rolling(3, min_periods=1).sum().values
    wind_ramp_1h = np.vstack([np.zeros((1, N_NODES)), np.diff(pivot["wind_speed_10m"], axis=0)])

    elec = electricity.set_index("datetime").reindex(time_index).ffill()
    gb_demand = np.repeat(elec["gb_demand_MW"].values[:, None], N_NODES, axis=1)
    gb_wind_cf = np.repeat(elec["gb_wind_cf"].values[:, None], N_NODES, axis=1)
    gb_solar_cf = np.repeat(elec["gb_solar_cf"].values[:, None], N_NODES, axis=1)

    stack = np.stack([
        pivot["wind_speed_10m"], gust_cubed, pivot["wind_gusts_10m"], wind_ramp_1h,
        pivot["precipitation"], rain_accum_3h, pivot["temperature_2m"],
        pivot["relative_humidity_2m"], pivot["surface_pressure"], pivot["cloud_cover"],
        gb_demand, gb_wind_cf, gb_solar_cf,
    ], axis=-1).astype("float32")

    assert stack.shape == (T, N_NODES, len(RAW_DYNAMIC_FEATURES))
    log(f"Engineered RAW dynamic feature tensor: {stack.shape} "
        f"(T={T:,} hours, N={N_NODES} nodes, F={len(RAW_DYNAMIC_FEATURES)} candidate features)")
    return stack, time_index


def standardise(x: np.ndarray) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    mu = x.reshape(-1, x.shape[-1]).mean(0)
    sd = x.reshape(-1, x.shape[-1]).std(0) + 1e-6
    return (x - mu) / sd, mu, sd


def compute_vif(X: np.ndarray) -> np.ndarray:
    n, p = X.shape
    Xc = X - X.mean(0)
    vifs = np.zeros(p)
    for j in range(p):
        y = Xc[:, j]
        others = np.delete(Xc, j, axis=1)
        beta, *_ = np.linalg.lstsq(others, y, rcond=None)
        y_hat = others @ beta
        ss_res = np.sum((y - y_hat) ** 2)
        ss_tot = np.sum(y ** 2) + 1e-12
        r2 = min(max(1 - ss_res / ss_tot, 0.0), 0.999999)
        vifs[j] = 1.0 / (1.0 - r2)
    return vifs


def prune_correlated_features(feature_stack: np.ndarray, feat_names: List[str],
                               protect: Tuple[str, ...] = ("gust_cubed", "wind_gusts_10m",
                                                            "precipitation", "wind_ramp_1h"),
                               vif_threshold: float = VIF_THRESHOLD,
                               max_subsample: int = 20000
                               ) -> Tuple[np.ndarray, List[str], pd.DataFrame]:
    flat = feature_stack.reshape(-1, feature_stack.shape[-1]).astype("float64")
    if flat.shape[0] > max_subsample:
        idx = RNG.choice(flat.shape[0], size=max_subsample, replace=False)
        flat = flat[idx]
    mu, sd = flat.mean(0), flat.std(0) + 1e-9
    flat_std = (flat - mu) / sd

    names = list(feat_names)
    keep_mask = np.ones(len(names), dtype=bool)
    history = []
    while True:
        active_idx = np.where(keep_mask)[0]
        if len(active_idx) <= 2:
            break
        vifs = compute_vif(flat_std[:, active_idx])
        vif_map = {names[active_idx[i]]: vifs[i] for i in range(len(active_idx))}
        droppable = {n: v for n, v in vif_map.items() if n not in protect}
        if not droppable or max(droppable.values()) < vif_threshold:
            break
        worst = max(droppable, key=droppable.get)
        history.append((worst, round(vif_map[worst], 2)))
        keep_mask[names.index(worst)] = False

    kept_idx = np.where(keep_mask)[0]
    pruned_names = [names[i] for i in kept_idx]
    pruned_stack = feature_stack[..., kept_idx]

    log(f"Multicollinearity screening (VIF threshold={vif_threshold}): dropped "
        f"{len(history)} feature(s) -- {history if history else '(none)'}; "
        f"retained {len(pruned_names)}/{len(names)} dynamic features for modelling: "
        f"{pruned_names}")
    report = pd.DataFrame(history, columns=["dropped_feature", "VIF_at_removal"])
    if report.empty:
        report = pd.DataFrame([{"dropped_feature": None, "VIF_at_removal": None}]).iloc[0:0]
    save_csv(report, TAB_DIR / "table12_multicollinearity_screening.csv", index=False)
    log("Saved table12_multicollinearity_screening.csv")
    return pruned_stack, pruned_names, report


