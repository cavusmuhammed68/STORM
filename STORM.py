def gradient_saliency(model, X, static_t, horizon_idx, n_subset=200) -> np.ndarray:
    sub = RNG.choice(len(X), size=min(n_subset, len(X)), replace=False)
    Xs = torch.tensor(X[sub], requires_grad=True)
    model.eval()
    logits = model(Xs, static_t)
    if isinstance(logits, tuple):
        logits = logits[0]
    target = logits[..., horizon_idx].sum()
    target.backward()
    saliency = Xs.grad.abs().mean(dim=(0, 2)).cpu().numpy()
    return saliency


